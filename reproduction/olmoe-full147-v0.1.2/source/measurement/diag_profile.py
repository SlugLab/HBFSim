def phase_window(value):
    need(value.get('schema') == 'hbfsim.hybrid_phase_window.v1' and
         value.get('requested_flag') == '1' and value.get('diagnostic_status') == 'PASS' and
         value.get('snapshot_error') is None and value.get('validation_errors') == [], 'actual phase window')
    before, after, delta = value.get('before', {}), value.get('after', {}), value.get('delta', {})
    fields = ('requests_submitted', 'requests_completed', 'fast_requests', 'reference_requests',
              'fast_modeled_ns', 'fast_total_ns', 'reference_total_ns', 'reference_ring_wait_ns',
              'reference_post_target_loop_wait_ns')
    need(before.get('schema') == after.get('schema') == MAGIC and
         before.get('enabled') == after.get('enabled') == 1 and
         type(before.get('generation')) is int and before['generation'] > 0 and
         before.get('generation') == after.get('generation'), 'actual phase schema/generation')
    need(set(delta) == set(fields), 'exact delta population')
    for key in fields:
        need(type(before.get(key)) is int and type(after.get(key)) is int and
             type(delta.get(key)) is int and 0 <= before[key] <= after[key] and
             delta[key] == after[key] - before[key], 'counter delta: ' + key)
    need(delta['requests_submitted'] == delta['requests_completed'] == delta['reference_requests'] > 0 and
         delta['reference_total_ns'] > 0 and
         delta['reference_ring_wait_ns'] + delta['reference_post_target_loop_wait_ns'] <= delta['reference_total_ns'] and
         (delta['fast_requests'] == 0 or delta['fast_total_ns'] > 0), 'request population/partition')
    return {'status': 'ACTUAL_DIAG_N_PHASE_WINDOW_VALIDATED',
            'denominator': 'reference_request_ns; concurrent request SUM, not generation wall'}


def terminal_join(spec, terminal):
    """One real nominal diagnostic result; no zero-wait synthesis or new control."""
    import runpy
    need(terminal.get('success') is True, 'actual owner cell terminal success missing')
    run = Path(terminal['run'])
    plan = json.loads((run / 'plan.json').read_bytes())
    route(spec, [plan])
    root_revision(plan)
    result = json.loads((run / 'result/cell/result.json').read_bytes())
    report = json.loads((run / 'MODEL_VALIDATION.json').read_bytes())
    need(report.get('status') == 'MODEL_CONNECTED_PASS_CANDIDATE_ONLY_MEASUREMENT' and
         report.get('validated_plan_sha256') == sha((run / 'plan.json').read_bytes()) and
         report.get('normal_live_binding', {}).get('phase_mode_actual_pre_generation') == 'ON_HEADER_MAGIC',
         'actual bound diagnostic validation')
    phase_window(result.get('hybrid_phase_window', {}))
    cohort = runpy.run_path(str(Path(__file__).with_name('scientific_cohort.py')))
    cohort['timing'](result)
    rows = {row['name']: row for row in spec['adopted_measurements']['files']}
    for role in ('U', 'N'):
        row = rows[role + '_result_cell_result.json']
        prior = load_binding({'path': row['path'], 'sha256': row['sha256']})
        need(prior.get('scientific_status') == result.get('scientific_status') == 'COMPLETE' and
             prior.get('request_terminal_status') == result.get('request_terminal_status') == 'success',
             'complete original adopted/current scientific result')
        need(all(key in prior and key in result and prior[key] == result[key]
                 for key in cohort['COMMON']), 'actual adopted/current scientific cohort: ' + role)
    timeline_path = run / 'result/cell/diag-host-timeline.json'
    timeline = json.loads(timeline_path.read_bytes())
    need(timeline.get('schema') == 'hbfsim.diag_n_host_timeline.v1' and
         timeline.get('complete') is True and type(timeline.get('wall_ns')) is int and
         timeline['wall_ns'] > 0 and
         sum(row['ns'] for row in timeline.get('disjoint_spans', [])) == timeline['wall_ns'],
         'same-attempt host timeline')
    return {'schema': 'hbfsim.diag_n_measurement_acceptance.v1',
            'status': 'ACTUAL_NOMINAL_DIAGNOSTIC_MEASUREMENT_VALIDATED', 'role': ROLE,
            'profile': PROFILE, 'nominal_modeled_wait': True,
            'plan_sha256': sha((run / 'plan.json').read_bytes()),
            'model_validation_sha256': sha((run / 'MODEL_VALIDATION.json').read_bytes()),
            'result_sha256': sha((run / 'result/cell/result.json').read_bytes()),
            'timeline_sha256': sha(timeline_path.read_bytes()),
            'interpretation': 'Single new nominal diagnostic attempt with adopted input/output controls; '
                'not old N/Z same-implementation-domain PASS or zero-wait synthesis.'}


