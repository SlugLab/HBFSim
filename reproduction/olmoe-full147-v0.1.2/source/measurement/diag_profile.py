def need(value, message):
    if not value:
        raise RuntimeError('DIAG_N: ' + message)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def load_binding(row):
    need(type(row) is dict and set(row) == {'path', 'sha256'}, 'exact file binding')
    path = Path(row['path'])
    need(path.is_absolute() and not path.is_symlink() and path.is_file() and
         str(path.resolve(strict=True)) == str(path), 'canonical regular binding')
    raw = path.read_bytes()
    need(sha(raw) == row['sha256'], 'bound bytes changed')
    return json.loads(raw)


