def requested(plan):
    """Unknown/incomplete opt-ins fail closed rather than becoming legacy OFF."""
    env = plan.get('env', {})
    active = (plan.get('cell_id') == ROLE or plan.get('diagnostic_profile') is not None or
              plan.get('measurement_role') is not None or
              'diagnostic_profile_binding' in plan or
              'HBFSIM_DIAG_PROFILE_PATH' in env or
              'HBFSIM_DIAG_PROFILE_SHA256' in env or
              env.get('HBFSIM_HYBRID_PHASE_DIAG_V1') == '1')
    if not active:
        return False
    need(plan.get('cell_id') == ROLE and plan.get('measurement_role') == ROLE and
         plan.get('diagnostic_profile') == PROFILE and
         plan.get('consumer_policy') == 'CANDIDATE_ONLY' and
         plan.get('backend') == 'legacy_hbf' and plan.get('wait_mode') == 'nominal' and
         env.get('HBFSIM_HBF_WAIT_MODE') == 'nominal' and
         env.get('HBFSIM_HYBRID_PHASE_DIAG_V1') == '1' and
         env.get('HBFSIM_STORAGE_BYTE_IDENTITY_V1') == '1', 'role/profile/nominal/phase discriminator')
    return True


def validate_profile_data(plan, profile):
    need(requested(plan), 'profile not requested')
    need(type(profile) is dict and set(profile) == {
        'schema', 'role', 'profile', 'extension_sha256', 'frozen',
        'runner_sha256', 'contract_sha256', 'source_revision', 'native_source_regions'} | ({'optimized_full147_binding','optimized_full147_helper'} if 'optimized_full147_binding' in plan else set()), 'profile exact schema')
    need(profile['schema'] == 'hbfsim.diag_n_profile.v1' and
         profile['role'] == ROLE and profile['profile'] == PROFILE and
         profile['extension_sha256'] == plan.get('new_extension_sha256') == EXTENSION and
         plan['env'].get('HBFSIM_RANGE_OBSERVATION_EXTENSION_SHA256') == EXTENSION,
         'observer extension identity')
    qualification = optimized(plan, profile)
    frozen = FROZEN if qualification is None else qualification['frozen']
    need(profile['frozen'] == frozen and
         all(plan.get(key) == value for key, value in frozen.items()), 'unchanged helper/full9/science closure')
    need(profile['runner_sha256'] == plan.get('runner_sha256') and
         profile['contract_sha256'] == sha(Path(__file__).read_bytes()), 'runner/contract source identity')
    source = Path(plan['runner_source_path'])
    need(source.is_absolute() and not source.is_symlink() and source.is_file() and
         sha(source.read_bytes()) == profile['runner_sha256'], 'actual runner source')
    validate_revision_rows(profile['source_revision'])
    need(profile['source_revision']['runner_sha256']['new'] == profile['runner_sha256'],
         'runner revision must join actual runner')
    regions = profile['native_source_regions']
    need(type(regions) is dict and set(regions) == {'model_input', 'generate_call', 'generation_timer'},
         'exact native comparability regions')
    for pair in regions.values():
        need(type(pair) is dict and set(pair) == {'old', 'new'} and
             all(type(v) is str and len(v) == 64 and all(c in '0123456789abcdef' for c in v)
                 for v in pair.values()), 'native comparability region pair')
    return profile


